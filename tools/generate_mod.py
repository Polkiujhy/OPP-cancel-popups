#!/usr/bin/env python3
"""Embed the canonical Galaxy in the editor's Custom Script element.

The editor is allowed to regenerate its Lib*.galaxy files: all executable
source is also present in Triggers. Never edit either generated file by hand.
CustomScript XML is verified against Alzarath's SimpleBaseDiscovery.SC2Lib;
MapInit and custom action FunctionDefs against NativeLib.TriggerLib.
"""
import argparse
from pathlib import Path
import textwrap
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MOD = ROOT / 'files'
SOURCES = ['opp_popup_ui.galaxy', 'opp_events.galaxy', 'opp_units.galaxy', 'opp_research.galaxy', 'opp_bootstrap.galaxy']


def script_text(source):
    # TriggerData/Library/Element/ScriptCode has XML depth three. The editor
    # removes its four-space-per-level XML margin from EVERY code line.
    # Match the actual persisted ScriptCode blocks in WCS GameHeart/PlusPlus.
    return '\n' + textwrap.indent(source.rstrip() + '\n', ' ' * 16, lambda line: True) + ' ' * 12


def products():
    source = '\n'.join((ROOT / 'source' / name).read_text().rstrip() for name in SOURCES) + '\n'
    root = ET.Element('TriggerData')
    lib = ET.SubElement(root, 'Library', Id='C0DEC0DE')
    libroot = ET.SubElement(lib, 'Root')
    ET.SubElement(libroot, 'Item', Type='CustomScript', Library='C0DEC0DE', Id='00000001')
    ET.SubElement(libroot, 'Item', Type='Trigger', Library='C0DEC0DE', Id='00000002')
    script = ET.SubElement(lib, 'Element', Type='CustomScript', Id='00000001')
    ET.SubElement(script, 'Name').text = 'OPP Cancel Popups - generated canonical source'
    ET.SubElement(script, 'ScriptCode').text = script_text(source)
    trigger = ET.SubElement(lib, 'Element', Type='Trigger', Id='00000002')
    ET.SubElement(trigger, 'Identifier').text = 'Initialization'
    ET.SubElement(trigger, 'Event', Type='FunctionCall', Library='C0DEC0DE', Id='00000010')
    ET.SubElement(trigger, 'Action', Type='FunctionCall', Library='C0DEC0DE', Id='00000011')
    event = ET.SubElement(lib, 'Element', Type='FunctionCall', Id='00000010')
    ET.SubElement(event, 'FunctionDef', Type='FunctionDef', Library='Ntve', Id='00000120')
    action = ET.SubElement(lib, 'Element', Type='FunctionCall', Id='00000011')
    ET.SubElement(action, 'FunctionDef', Type='FunctionDef', Library='Ntve', Id='00000123')
    ET.SubElement(action, 'ScriptCode').text = script_text('OPP_Init();')
    ET.indent(root, space='    ')
    xml = ET.tostring(root, encoding='unicode', xml_declaration=True) + '\n'
    galaxy = '''// Generated by tools/generate_mod.py. Do not edit.
include "TriggerLibs/NativeLib"
include "LibC0DEC0DE_h"

''' + source + '''
trigger libC0DEC0DE_gt_Initialization;
bool libC0DEC0DE_gt_Initialization_Func (bool testConds, bool runActions) {
    if (!runActions) { return true; }
    OPP_Init();
    return true;
}
void libC0DEC0DE_gt_Initialization_Init () {
    libC0DEC0DE_gt_Initialization = TriggerCreate("libC0DEC0DE_gt_Initialization_Func");
    TriggerAddEventMapInit(libC0DEC0DE_gt_Initialization);
}
bool libC0DEC0DE_InitLib_completed = false;
void libC0DEC0DE_InitLib () {
    if (libC0DEC0DE_InitLib_completed) { return; }
    libC0DEC0DE_InitLib_completed = true;
    libC0DEC0DE_gt_Initialization_Init();
}
'''
    header = '''// Generated by tools/generate_mod.py. Do not edit.
include "TriggerLibs/natives"
void libC0DEC0DE_InitLib ();
'''
    return {'Triggers': xml, 'Base.SC2Data/LibC0DEC0DE.galaxy': galaxy,
            'Base.SC2Data/LibC0DEC0DE_h.galaxy': header}


def generate(folder=MOD, check=False):
    drift = []
    for name, content in products().items():
        target = folder / name
        if check:
            if not target.exists() or target.read_text() != content:
                drift.append(name)
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
    if drift:
        raise SystemExit('Generated source drift: ' + ', '.join(drift))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--folder', type=Path, default=MOD)
    args = parser.parse_args()
    generate(args.folder, args.check)
